def _build(machines: tuple[StateMachine, ...]) -> Mapping[str, StateMachine]:
    registry: dict[str, StateMachine] = {}
    ts_names: set[str] = set()
    for machine in machines:
        if machine.name in registry:
            raise ValueError("duplicate state machine %r" % machine.name)
        if len(set(machine.states)) != len(machine.states):
            raise ValueError("%s repeats a state" % machine.name)
        known = set(machine.states)
        for subset in machine.subsets:
            if not set(subset.states) <= known:
                raise ValueError("%s.%s names a state the machine does not have" % (machine.name, subset.name))
        if machine.transitions is not None:
            if set(machine.transitions) != known:
                raise ValueError("%s transitions must have one entry per state" % machine.name)
            for targets in machine.transitions.values():
                if not set(targets) <= known:
                    raise ValueError("%s has a transition to an unknown state" % machine.name)
        for ts_name in (machine.ts_type, *(subset.ts_type for subset in machine.subsets)):
            if ts_name is None:
                continue
            if ts_name in ts_names:
                raise ValueError("duplicate TypeScript type %r" % ts_name)
            ts_names.add(ts_name)
        registry[machine.name] = machine
    return MappingProxyType(registry)


REGISTRY: Mapping[str, StateMachine] = _build(_MACHINES)


def machine(name: str) -> StateMachine:
    """Return the registered machine called ``name``."""
    return REGISTRY[name]
