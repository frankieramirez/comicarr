"""The registry of Comicarr's cross-layer state machines.

One entry per machine whose states cross a boundary: stored in a column and
read by another module, sent over the HTTP API, or published in an MCP tool
schema. An entry says what the states are, where they are stored, which module
owns the writes, and how a move between states is enforced.

Three things are derived from, or pinned to, this file:

  frontend/src/types/states.generated.ts
      generated by ``scripts/generate_state_types.py``; ``npm run lint``
      fails when it is stale.
  tests/unit/test_state_machine_registry.py
      pins every entry to the enum, constant or schema that enforces it, so
      neither side can change alone.
  frontend/src/lib/statusTone.ts
      must give every issue and series state a label and a colour, or the
      frontend does not compile.

Nothing here runs at request time. No write is checked against this registry:
an unknown state is still stored and still rendered, as it was before. CI is
the gate. Contract and inventory: ``docs/architecture/state-machines.md``.

This module is a stdlib-only leaf. The generator loads it by path on a bare
interpreter, so it must not import anything from ``comicarr``.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from types import MappingProxyType
from typing import Mapping


@dataclass(frozen=True)
class StateSubset:
    """A named group of one machine's states that other code branches on."""

    name: str
    states: tuple[str, ...]
    summary: str
    #: Name of the exported TypeScript type; None keeps the subset backend-only.
    ts_type: str | None = None


@dataclass(frozen=True)
class StateMachine:
    """One machine: its states and how a move between them is enforced."""

    name: str
    summary: str
    #: Every state, spelled exactly as it is stored and sent. Order is the
    #: order of the generated TypeScript union.
    states: tuple[str, ...]
    #: ``table.column``, or None when the state is computed and never stored.
    stored_in: str | None
    #: The module that owns the writes, or the computation for a projection.
    owner: str
    #: How a move is enforced today, in one line. ``none`` means any writer
    #: may store any value.
    enforced_by: str
    #: Name of the exported TypeScript type; None keeps the machine backend-only.
    ts_type: str | None = None
    subsets: tuple[StateSubset, ...] = ()
    #: Legal moves, only where the owner enforces them. None means the owner
    #: enforces something other than an edge list, or nothing.
    transitions: Mapping[str, tuple[str, ...]] | None = field(default=None, hash=False)
    notes: str = ""

    def subset(self, name: str) -> tuple[str, ...]:
        for candidate in self.subsets:
            if candidate.name == name:
                return candidate.states
        raise KeyError("%s has no subset %r" % (self.name, name))

    def allows(self, current: str, target: str) -> bool | None:
        """Whether ``current -> target`` is a declared move; None if undeclared."""
        if self.transitions is None:
            return None
        return target in self.transitions.get(current, ())


