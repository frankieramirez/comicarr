"""Emit the frontend state unions from the state machine registry.

    python3 scripts/generate_state_types.py           # rewrite the committed module
    python3 scripts/generate_state_types.py --check    # fail if it is stale

Output is committed and must be regenerated whenever a machine or subset that
names a ``ts_type`` changes in ``comicarr/app/common/state_machines.py``. The
``--check`` mode is wired into ``npm run lint`` and the Backend Lint CI job;
``npm run lint:fix`` rewrites the module.

``--check`` compares in memory and prints a unified diff. It never touches the
working tree, so a failing lint leaves nothing to clean up.

Like ``generate_config_types.py``, this script loads its input *by path* and
not through the ``comicarr`` package, so it runs on a bare interpreter with no
project dependencies installed.

Each exported machine becomes a readonly array of its states plus the union
type of that array, so the frontend can both type a value and iterate the
vocabulary. The output is Prettier-clean by construction.
"""

from __future__ import annotations

import argparse
import difflib
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

REGISTRY_PY = ROOT / "comicarr" / "app" / "common" / "state_machines.py"
OUTPUT = ROOT / "frontend" / "src" / "types" / "states.generated.ts"

# Prettier's default print width; a longer statement is broken the way
# Prettier breaks it.
WIDTH = 80


def _load_registry() -> dict:
    """Load ``state_machines.py`` by path, bypassing ``comicarr/__init__.py``."""
    spec = importlib.util.spec_from_file_location("comicarr_state_machines", REGISTRY_PY)
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolves the owning module out of sys.modules while it
    # processes @dataclass, so register before executing.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module.REGISTRY


def _const_name(ts_type: str) -> str:
    """``IssueDisplayState`` -> ``ISSUE_DISPLAY_STATE_VALUES``."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", ts_type).upper() + "_VALUES"


def _render_export(ts_type: str, states: tuple[str, ...], comment: str) -> list[str]:
    const = _const_name(ts_type)
    values = ", ".join('"%s"' % state for state in states)
    array = "export const %s = [%s] as const;" % (const, values)
    if len(array) > WIDTH:
        array = "\n".join(["export const %s = [" % const] + ['  "%s",' % state for state in states] + ["] as const;"])
    alias = "export type %s = (typeof %s)[number];" % (ts_type, const)
    if len(alias) > WIDTH:
        alias = "export type %s =\n  (typeof %s)[number];" % (ts_type, const)
    return ["/** %s */" % comment, array, alias]


def render() -> str:
    registry = _load_registry()

    out = [
        "// GENERATED by scripts/generate_state_types.py — do not edit by hand.",
        "// Source of truth: comicarr/app/common/state_machines.py",
    ]
    exported = 0
    for machine in registry.values():
        if machine.ts_type:
            out.append("")
            out.extend(_render_export(machine.ts_type, machine.states, machine.summary))
            exported += 1
        for subset in machine.subsets:
            if subset.ts_type:
                out.append("")
                out.extend(_render_export(subset.ts_type, subset.states, subset.summary))
                exported += 1

    print("# %d machines registered, %d types exported" % (len(registry), exported), file=sys.stderr)
    # The single trailing newline is the one Prettier wants; a blank final line
    # would fail `npm run format:check`.
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed module is stale, without rewriting it",
    )
    args = parser.parse_args(argv)

    generated = render()
    relative = OUTPUT.relative_to(ROOT)

    if not args.check:
        OUTPUT.write_text(generated)
        return 0

    committed = OUTPUT.read_text() if OUTPUT.exists() else ""
    if committed == generated:
        return 0

    diff = difflib.unified_diff(
        committed.splitlines(keepends=True),
        generated.splitlines(keepends=True),
        fromfile="%s (committed)" % relative,
        tofile="%s (regenerated)" % relative,
    )
    sys.stdout.writelines(diff)
    print(
        "\n%s is stale. Run `npm run lint:fix:generated` (or "
        "`python3 scripts/generate_state_types.py`) and commit the result." % relative,
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
